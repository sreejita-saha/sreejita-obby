-- Apply with `supabase db push` (or paste into the Supabase SQL Editor).
-- Feedback is written only by the Edge Function using the service-role key.

create schema if not exists private;

create table if not exists public.ratings (
  id bigint generated by default as identity primary key,
  rating smallint not null,
  comment text not null default '',
  created_at timestamptz not null default now()
);

alter table public.ratings enable row level security;
revoke all on table public.ratings from anon, authenticated;

alter table public.ratings
  drop constraint if exists ratings_rating_range,
  add constraint ratings_rating_range check (rating between 1 and 5),
  drop constraint if exists ratings_comment_length,
  add constraint ratings_comment_length check (char_length(comment) <= 300);

-- A hashed IP + user-agent fingerprint is retained only long enough to enforce
-- the submission limit; it is never exposed through the public API.
create table if not exists private.rating_rate_limits (
  fingerprint text primary key,
  last_submitted_at timestamptz not null default now()
);
alter table private.rating_rate_limits enable row level security;
revoke all on table private.rating_rate_limits from public, anon, authenticated;

create or replace function public.submit_rating(
  p_rating smallint,
  p_comment text,
  p_fingerprint text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if p_rating not between 1 and 5 then
    raise exception 'rating must be between 1 and 5' using errcode = '22023';
  end if;

  if p_comment is null or char_length(p_comment) > 300
    or p_comment ~ '[[:cntrl:]]' then
    raise exception 'invalid comment' using errcode = '22023';
  end if;

  if p_fingerprint is null or char_length(p_fingerprint) <> 64
    or p_fingerprint !~ '^[0-9a-f]{64}$' then
    raise exception 'invalid request' using errcode = '22023';
  end if;

  delete from private.rating_rate_limits
  where last_submitted_at < now() - interval '1 day';

  insert into private.rating_rate_limits (fingerprint, last_submitted_at)
  values (p_fingerprint, now())
  on conflict (fingerprint) do update
    set last_submitted_at = excluded.last_submitted_at
    where private.rating_rate_limits.last_submitted_at <= now() - interval '10 minutes';

  if not found then
    raise exception 'rate limit exceeded' using errcode = 'P0001';
  end if;

  insert into public.ratings (rating, comment)
  values (p_rating, btrim(p_comment));
end;
$$;

revoke all on function public.submit_rating(smallint, text, text) from public, anon, authenticated;
grant execute on function public.submit_rating(smallint, text, text) to service_role;
